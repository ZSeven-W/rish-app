export const TRANSLATIONS: Readonly<
  Record<ResolvedLocale, Readonly<Record<TranslationKey, string>>>
> = Object.freeze({
  'en-US': Object.freeze(enUS),
  'zh-CN': Object.freeze(zhCN),
});

function interpolate(template: string, params?: TranslationParams): string {
  if (params === undefined) {
    return template;
  }
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/gu, (match, name) =>
    Object.prototype.hasOwnProperty.call(params, name)
      ? String(params[name])
      : match,
  );
}

export function translate(
  locale: ResolvedLocale,
  key: TranslationKey,
  params?: TranslationParams,
): string {
  const template = TRANSLATIONS[locale]?.[key] ?? enUS[key] ?? key;
  return interpolate(template, params);
}

export function createTranslator(locale: ResolvedLocale): Translator {
  return (key, params) => translate(locale, key, params);
}

/** Default English translator. Use createTranslator for the resolved app locale. */
export const t: Translator = createTranslator('en-US');
