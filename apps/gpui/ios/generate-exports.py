#!/usr/bin/env python3
"""Generate the reviewed exported-selector allowlist; never export private APIs.

Run --check in validation. A native API change requires regenerating and reviewing
Exports.inc, rather than exposing a new Objective-C selector automatically.
"""
import argparse
from pathlib import Path
import re

IOS = Path(__file__).resolve().parent
ROOT = IOS.parents[2]
MODULES = (
    "AgentPolicy AgentRuntime LocalAttachments LocalDocuments LocalEnvironments "
    "LocalGuest LocalMirrors LocalPrograms LocalProjectContext LocalProjects "
    "LocalRuntime LocalWorkspace LocalWorkspaces SessionSnapshots"
).split()
TYPE_CODES = {"id": "i", "NSString *": "s", "NSDictionary *": "d",
              "NSArray *": "a", "NSNumber *": "n", "BOOL": "b"}


def arguments(signature):
    return re.findall(r"(\w+)\s*:\s*\(([^)]+)\)", signature)


def record(module, name, parts, synchronous=False):
    if not synchronous:
        assert len(parts) >= 2, (module, name)
        assert "RishResolveBlock" in parts[-2][1], (module, name)
        assert "RishRejectBlock" in parts[-1][1], (module, name)
    params = parts if synchronous else parts[:-2]
    types = "".join(TYPE_CODES[re.sub(r"\b(?:nonnull|nullable|__unused)\s*", "", ty)]
                    for _, ty in params)
    selector = "".join(label + ":" for label, _ in parts)
    return f'  {{@"{module}", @"{name}", @"{selector}", "{types}", {"YES" if synchronous else "NO"}}},'


def generate():
    rows = []
    for module in MODULES + ["ShellInput", "ShellWorkspace", "ShellAssistant", "ShellRuntimeEngines", "TaskExperience"]:
        source = ((ROOT / "modules/rish/ios/Sources" / f"{module}Module.mm")
                  if module not in ["ShellInput", "ShellWorkspace", "ShellAssistant", "ShellRuntimeEngines", "TaskExperience"]
                  else IOS / "Sources" / f"{module}Module.m")
        content = source.read_text()
        # Keep the split LocalRuntime implementation in the same reviewed
        # allowlist. Only this named implementation include is scanned.
        if module == "LocalRuntime":
            for name in ("LocalRuntimeCustomProviders.inc", "LocalRuntimeProviderModels.inc"):
                include = f'#include "{name}"'
                assert content.count(include) == 1
                content = content.replace(include, (source.parent / name).read_text())
        assert f"RISH_NATIVE_MODULE({module})" in content
        if module == "AgentRuntime":
            exports = re.findall(r"^DSH_RUNTIME_EXPORT\(\s*(\w+)\s*,\s*(\w+)\s*,", content, re.M)
            assert exports
            for name, selector in exports:
                rows.append(record(module, name, [(selector, "id"),
                    ("resolver", "RishResolveBlock"), ("rejecter", "RishRejectBlock")]))
        else:
            exports = re.findall(r"RISH_NATIVE_METHOD\(\s*(\w+)\s*,(.*?)\)\s*\{", content, re.S)
            assert exports, module
            for name, signature in exports:
                rows.append(record(module, name, arguments(signature)))
        for signature in re.findall(r"RISH_NATIVE_SYNC\((.*?)\)\s*\{", content, re.S):
            parts = arguments(signature)
            rows.append(record(module, parts[0][0], parts, True))
    return ("// Generated by generate-exports.py; review changes to this allowlist.\n"
            "static const RishExport RishExports[] = {\n" + "\n".join(rows) + "\n};\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = IOS / "Sources/Exports.inc"
    generated = generate()
    if args.check:
        if not output.exists() or output.read_text() != generated:
            raise SystemExit("Native exports changed; regenerate and review Sources/Exports.inc")
        print("Native export allowlist is current")
    else:
        output.write_text(generated)
        print(f"Wrote {output}")
