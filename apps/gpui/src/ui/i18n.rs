    pub fn detect() -> Self {
        let lang =
            sys_locale::get_locale().unwrap_or_else(|| std::env::var("LANG").unwrap_or_default());
        if lang.to_lowercase().starts_with("zh") {
            Self::Zh
        } else {
            Self::En
        }
    }
    pub fn code(self) -> &'static str {
        if self == Self::Zh { "zh-CN" } else { "en-US" }
    }
